"""
실시간 설문 의견형 결과 요약 - 학생 답변 원문(이미 구분자로 합쳐진 문자열)을
받아 전반적인 분위기·다수의견·특이사항을 한국어로 요약하는 LangChain 체인.
exam_generator.py와 동일한 구조(프롬프트 템플릿 + LLM 인스턴스 함수)를 따른다.
"""

from llm_provider import get_openai_llm

_PROMPT_TEMPLATE = """당신은 수업 중 진행된 실시간 설문의 의견형 답변을 요약하는
보조 교사입니다. 아래 [학생 답변]에 실제로 적힌 내용만 근거로 삼으세요.
답변에 없는 내용·주제·감정을 추측하거나 지어내는 것은 절대 금지입니다.

[질문]
{question_text}

[학생 답변 - 각 답변은 "---" 로 구분됨]
{answers_text}

[요청]
먼저 각 답변이 실제로 해석 가능한 의견인지 판단하세요. 무작위 키보드
입력, 자음/모음만 나열된 문자열처럼 뜻을 알 수 없는 답변은 평가 대상에서
완전히 제외하세요.

해석 가능한 답변이 하나도 없다면(전부 의미를 알 수 없는 문자열이라면)
다른 내용을 절대 지어내지 말고 "의미를 파악할 수 있는 답변이 없습니다."
라고만 답하세요.

해석 가능한 답변이 있다면, 그 답변들만 근거로 다수 의견은 어느 쪽인지,
전반적인 분위기는 어떤지, 유독 부정적인 답변이 있다면 그 요지(없으면
언급하지 않음) - 이 세 가지만 자연스럽게 이어지는 문장으로 요약하세요.
답변에 실제로 없는 주제나 감정을 덧붙이지 마세요.

건수나 인원수를 구체적인 숫자·퍼센트로 세거나 언급하지 마세요("총 4건",
"2명은 ~", "75%는 ~" 같은 표현 금지, 최종 문장에는 등장하면 안 됨) -
다만 판단 자체는 아래 기준으로 비율을 가늠해서 내리세요:

- 같은 취지의 답변이 전체의 **절반(과반) 이상**이면 "대부분", "다수"라고
  분명하게 쓰세요.
- 가장 큰 비중이지만 과반에는 못 미치면(예: 넷 중 둘처럼 가장 많지만
  절반을 살짝 넘지 않는 정도) "가장 많이 나온 의견은 ~이다"처럼 그
  방향을 중심에 두되 "다수"라고 단정하지는 마세요.
- 여러 의견이 뚜렷한 쏠림 없이 비슷한 비중으로 나뉠 때만(예: 정확히
  반반이거나 서너 갈래로 고르게 흩어짐) "의견이 갈렸다"고 쓰세요.
  **한쪽이 나머지보다 눈에 띄게 많으면(예: 넷 중 셋) 절대 "갈렸다"나
  "판단하기 어렵다"고 얼버무리지 말고, 그 많은 쪽을 분명한 다수 의견으로
  말하세요.** 이 기준은 다수 의견 판단뿐 아니라 전반적인 분위기를
  판단할 때도 똑같이 적용하세요 - 한쪽으로 뚜렷하게 쏠려 있으면 분위기도
  분명하게 말하고, 정말 비슷한 비중으로 팽팽할 때만 "분위기를 판단하기
  어렵다"고 하세요.
- 비중이 아주 작은 소수 의견(전체의 1/5 이하 정도)은 "소수 의견으로는
  ~"처럼 짧게만 덧붙이고, 전체 판단에 영향을 주지 마세요.

문장을 쓰기 전에 이 기준으로 먼저 판단을 내린 뒤, 문단 전체에서 그
판단을 일관되게 유지하세요(앞에서는 한쪽이 다수인 것처럼 쓰다가 뒤에서
"갈렸다"고 뒤집는 등, 같은 요약 안에서 앞뒤 판단이 모순되면 안 됩니다).

답변을 하나씩 나열하거나 그대로 인용하지 마세요(전체 답변 원문은 화면
아래에 이미 따로 표시됩니다). "의견이 다양하게 나타났다" 같은 내용 없는
상투적 문장으로 끝내지 말고 항상 구체적인 방향이나 내용을 말하세요.
글머리 기호나 번호, 줄바꿈 없이 2~3문장 이내의 자연스러운 한 문단으로
한국어로 작성하세요.
"""


def summarize(question_text: str, answers_text: str) -> str:
    llm = get_openai_llm()
    prompt = _PROMPT_TEMPLATE.format(
        question_text=question_text, answers_text=answers_text
    )
    result = llm.invoke(prompt)
    return result.content
